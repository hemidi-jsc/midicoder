"""
Query utilities for accessing and filtering indexed context data.

This module provides helper functions to load, search, and filter the context
files generated by the indexing process. It implements the query tools
described in Section 5-6 of the technical documentation.

Examples:
    Load all symbols and search for User-related items:
    
        from midicoder.context.query import load_symbols, search_symbols
        
        symbols = load_symbols('.midicoder/context')
        user_symbols = search_symbols(r'User', symbols)
        
    Filter exemplars by kind:
    
        from midicoder.context.query import load_exemplars, filter_exemplars_by_kind
        
        exemplars = load_exemplars('.midicoder/context')
        handlers = filter_exemplars_by_kind('command_handler', exemplars)
        
    Get all entry points:
    
        from midicoder.context.query import load_entrypoints
        
        entrypoints = load_entrypoints('.midicoder/context')
"""

import fnmatch
import json
import re
from difflib import unified_diff
from pathlib import Path
from typing import Any, Dict, List, Optional

# Type aliases for better readability
Symbol = Dict[str, Any]
EntryPoint = Dict[str, Any]
Seam = Dict[str, Any]
Exemplar = Dict[str, Any]
Profile = Dict[str, Any]
Manifest = Dict[str, Any]


def load_symbols(context_dir: str = ".midicoder/context") -> List[Symbol]:
    """
    Load all symbols from symbols.json.

    Args:
        context_dir: Path to the context directory (default: .midicoder/context)

    Returns:
        List of symbol dictionaries containing name, kind, file, line, signature

    Example:
        >>> symbols = load_symbols()
        >>> print(f"Total symbols: {len(symbols)}")
        >>> print(f"First symbol: {symbols[0]['name']}")
    """
    symbols_path = Path(context_dir) / "symbols.json"

    if not symbols_path.exists():
        return []

    with open(symbols_path, "r", encoding="utf-8") as f:
        return json.load(f)


