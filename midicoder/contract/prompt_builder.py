def build_contract_context_block(*, context: dict[str, Any]) -> str:
    """Build context block for contract generation."""
    context_block = json.dumps(context, indent=2, ensure_ascii=False)
    return "\n".join(
        [
            "Project context (JSON):",
            context_block,
        ]
    )


