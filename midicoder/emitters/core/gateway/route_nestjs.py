@dataclass
class NestJSWebhookEmitter:
    """Emitter de sinh webhook handler cho NestJS."""

    def emit(
        self,
        collection: RouteCollection,
        output_dir: Path,
    ) -> dict[str, str]:
        """Emit webhook handler files."""
        files: dict[str, str] = {}
        if not collection.webhooks:
            return files

        webhooks_dir = output_dir / "webhooks"
        webhooks_dir.mkdir(parents=True, exist_ok=True)

        for webhook in collection.webhooks:
            filename = f"{self._to_kebab_case(webhook.event_type)}-handler.ts"
            content = self._emit_webhook_file(webhook)
            files[str(webhooks_dir / filename)] = content

        return files

    def _emit_webhook_file(self, webhook: WebhookHandler) -> str:
        """Sinh webhook handler file."""
        handler_name = self._to_pascal_case(webhook.event_type) + "WebhookHandler"
        path = webhook.path
        parts = path.split("/")
        controller_path = parts[1] if len(parts) > 1 else ""
        post_path = parts[-1] if len(parts) > 1 else path

        lines = [
            '"""',
            f"Webhook Handler: {webhook.event_type}",
            f"Path: {path}",
            "Auto-generated by Midicoder CE.",
            '"""',
            "",
            "import { Controller, Post, Body, Headers, UnauthorizedException } from '@nestjs/common';",
            "import * as crypto from 'crypto';",
            "",
            f"@Controller('{controller_path}')",
            f"export class {handler_name} {{",
            "",
            f"  @Post('{post_path}')",
            "  async handleWebhook(",
            "    @Body() payload: Record<string, any>,",
        ]

        if webhook.auth_config and webhook.verify_signature:
            lines.append(f"    @Headers('{webhook.auth_config.header_name}') signature: string,")

        lines.append("  ): Promise<{ status: string }> {")

        if webhook.verify_signature:
            lines.append("    // Verify HMAC signature")
            lines.append("    const secret = process.env.WEBHOOK_SECRET || '';")
            lines.append("    const expected = crypto.createHmac('sha256', secret)")
            lines.append("      .update(JSON.stringify(payload))")
            lines.append("      .digest('hex');")
            lines.append("    if (!crypto.timingSafeEqual(Buffer.from(expected), Buffer.from(signature || ''))) {")
            lines.append("      throw new UnauthorizedException('Invalid signature');")
            lines.append("    }")
            lines.append("")

        lines.append(f"    // TODO: Wire to handler: {webhook.handler_id}")
        lines.append('    return { status: "ok" };')
        lines.append("  }")
        lines.append("}")
        lines.append("")

        return "\n".join(lines)

    @staticmethod
    def _to_kebab_case(name: str) -> str:
        s1 = re.sub("(.)([A-Z][a-z]+)", r"\1-\2", name)
        return re.sub("([a-z0-9])([A-Z])", r"\1-\2", s1).lower()

    @staticmethod
    def _to_pascal_case(name: str) -> str:
        return "".join(word.capitalize() for word in name.replace("-", " ").replace("_", " ").split())