@dataclass
class NestJSGraphQLResolverEmitter:
    """Emitter de sinh GraphQL resolver files cho NestJS."""

    def emit(
        self,
        collection: RouteCollection,
        output_dir: Path,
    ) -> dict[str, str]:
        """Emit GraphQL resolver files."""
        files: dict[str, str] = {}
        if not collection.resolvers:
            return files

        graphql_dir = output_dir / "graphql"
        graphql_dir.mkdir(parents=True, exist_ok=True)

        for resolver in collection.resolvers:
            filename = f"{self._to_kebab_case(resolver.id)}.resolver.ts"
            content = self._emit_resolver_file(resolver)
            files[str(graphql_dir / filename)] = content

        return files

    def _emit_resolver_file(self, resolver: GraphQLResolver) -> str:
        """Sinh resolver file cho mot GraphQL resolver."""
        type_name = self._to_pascal_case(resolver.id)
        op_decorator = "Query" if resolver.operation.value == "query" else "Mutation"

        lines = [
            '"""',
            f"GraphQL Resolver: {resolver.id}",
            "Auto-generated by Midicoder CE.",
            '"""',
            "",
            f"import {{ {op_decorator}, Resolver, Args }} from '@nestjs/graphql';",
            f"import {{ {type_name}Output }} from './{self._to_kebab_case(resolver.id)}.dto';",
            "",
            f"@Resolver('{self._to_pascal_case(resolver.type_name)}')",
            f"export class {type_name}Resolver {{",
            "",
            f"  @{op_decorator.lower()}(() => {type_name}Output)",
        ]

        args_str = ""
        if resolver.args:
            args_str = ", ".join(
                f"@Args('{a.name}') {a.name}: {self._ts_type(a.arg_type)}"
                for a in resolver.args
            )

        func_name = self._to_camel_case(resolver.id)
        lines.append(f"  async {func_name}({args_str}): Promise<{type_name}Output> {{")

        if resolver.tenant_scoped:
            lines.append("    // KPI-029: Tenant scope enforced")

        handler = self._to_camel_case(resolver.handler_id) + "Service"
        lines.append(f"    return this.{handler}.execute({{}})")
        lines.append("  }")
        lines.append("}")
        lines.append("")

        return "\n".join(lines)

    def _ts_type(self, type_str: str) -> str:
        type_map = {
            "String": "string", "Int": "number",
            "Float": "number", "Boolean": "boolean",
            "ID": "string", "Date": "Date",
        }
        return type_map.get(type_str, "string")

    @staticmethod
    def _to_kebab_case(name: str) -> str:
        s1 = re.sub("(.)([A-Z][a-z]+)", r"\1-\2", name)
        return re.sub("([a-z0-9])([A-Z])", r"\1-\2", s1).lower()

    @staticmethod
    def _to_pascal_case(name: str) -> str:
        return "".join(word.capitalize() for word in name.replace("-", " ").replace("_", " ").split())

    @staticmethod
    def _to_camel_case(name: str) -> str:
        words = name.replace("-", " ").replace("_", " ").split()
        return words[0].lower() + "".join(w.capitalize() for w in words[1:])


