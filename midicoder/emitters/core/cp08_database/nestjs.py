    def emit_read_model(self, read_model: ReadModel) -> dict[str, str]:
        """Sinh CQRS read model cho TypeORM."""
        lines: list[str] = []
        lines.append(f"// CQRS Read Model: {read_model.id}")
        lines.append(f"// Source: {read_model.source.value}")
        lines.append(f"// Refresh: {read_model.refresh_strategy.value}")
        lines.append("")
        lines.append("import { Entity, Column, PrimaryGeneratedColumn } from 'typeorm';")
        lines.append("")
        lines.append(f"@Entity('{read_model.table_name}')")
        lines.append(f"// Read model — {read_model.source.value}")
        lines.append(f"// Refresh strategy: {read_model.refresh_strategy.value}")
        lines.append(f"// Source tables: {', '.join(read_model.source_models)}")
        lines.append(f"export class {read_model.id} {{")
        lines.append("")
        lines.append(f"  @PrimaryGeneratedColumn('uuid')")
        lines.append(f"  id!: string;")

        for col in read_model.columns:
            orm_type = _TYPEORM_TYPE_MAP.get(col.column_type, "String")
            nullable = "" if col.required else ", nullable: true"
            lines.append("")
            lines.append(f"  @Column({{ type: '{orm_type}'{nullable} }})")
            lines.append(f"  {self._to_camel_case(col.name)}!: {orm_type};")

        lines.append("")
        lines.append(f"  @Column({{ type: 'timestamptz', nullable: true }})")
        lines.append(f"  lastRefreshedAt!: Date | null;")

        lines.append("")
        lines.append(f"  static refreshStrategy = '{read_model.refresh_strategy.value}';")

        strategy = read_model.refresh_strategy.value
        if strategy == "real_time":
            lines.append(f"  // Real-time: triggered by event handler on every write")
        elif strategy == "batch":
            lines.append(f"  // Batch: scheduled CRON job")
        elif strategy == "lazy":
            lines.append(f"  // Lazy: refreshed on first read after staleness threshold")
        elif strategy == "event_driven":
            lines.append(f"  // Event-driven: triggered by domain events")

        lines.append("}")
        lines.append("")

        filename = f"read_models/{self._to_kebab_case(read_model.table_name)}.entity.ts"
        return {filename: "\n".join(lines)}

    def emit_distributed_transaction(self, tx: DistributedTransaction) -> dict[str, str]:
        """Sinh distributed transaction coordinator (Saga/2PC/Outbox/TCC)."""
        lines: list[str] = []
        lines.append(f"// Distributed Transaction: {tx.id}")
        lines.append(f"// Protocol: {tx.protocol.value}")
        lines.append(f"// Timeout: {tx.timeout_seconds}s")
        lines.append("")
        lines.append("import { Injectable } from '@nestjs/common';")
        lines.append("")
        lines.append("")

        if tx.protocol.value == "saga":
            lines.append(f"enum SagaStep {{")
            for p in tx.participants:
                step_name = p.role.upper().replace(" ", "_")
                lines.append(f"  {step_name} = '{p.role}',")
                lines.append(f"  {step_name}_COMPENSATE = '{p.role}_compensate',")
            lines.append("}")
            lines.append("")
            lines.append("")
            lines.append(f"@Injectable()")
            lines.append(f"export class {tx.id.replace('-', '_').title().replace('_', '')}Saga {{")
            lines.append(f"  // Saga orchestrator for '{tx.id}'.")
            lines.append(f"  // Participants: {len(tx.participants)}")
            lines.append(f"  // Timeout: {tx.timeout_seconds}s")
            lines.append("")
            lines.append(f"  async execute() {{")
            lines.append(f"    // Execute saga steps forward; on failure, compensate.")
            lines.append(f"    const steps = Object.values(SagaStep);")
            lines.append(f"    for (const step of steps) {{")
            lines.append(f"      try {{")
            lines.append(f"        await this.runStep(step);")
            lines.append(f"      }} catch (error) {{")
            lines.append(f"        await this.compensate(error);")
            lines.append(f"        return false;")
            lines.append(f"      }}")
            lines.append(f"    }}")
            lines.append(f"    return true;")
            lines.append(f"  }}")
            lines.append("")
            lines.append(f"  private async compensate(error: any) {{")
            lines.append(f"    // Execute compensation steps in reverse.")
            lines.append(f"  }}")
            lines.append(f"")
            lines.append(f"  private async runStep(step: string) {{")
            lines.append(f"    switch (step) {{")
            for p in tx.participants:
                step_name = p.role.upper().replace(" ", "_")
                lines.append(f"      case SagaStep.{step_name}:")
                lines.append(f"        break;")
            lines.append(f"      default:")
            lines.append(f"        break;")
            lines.append(f"    }}")
            lines.append(f"  }}")
            lines.append("}")

        elif tx.protocol.value == "two_phase_commit":
            lines.append(f"@Injectable()")
            lines.append(f"export class {tx.id.replace('-', '_').title().replace('_', '')}Coordinator {{")
            lines.append(f"  // Two-Phase Commit coordinator for '{tx.id}'.")
            lines.append("")
            lines.append(f"  async prepare(): Promise<Record<string, boolean>> {{")
            lines.append(f"    // Phase 1: ask all participants to prepare.")
            lines.append(f"    const results: Record<string, boolean> = {{}};")
            for p in tx.participants:
                lines.append(f"    results['{p.role}'] = await this.prepare_{p.role.replace(' ', '_')}();")
            lines.append(f"    return results;")
            lines.append(f"  }}")
            lines.append("")
            lines.append(f"  async commit(): Promise<boolean> {{")
            lines.append(f"    // Phase 2: commit all if all prepared.")
            lines.append(f"    return true;")
            lines.append(f"  }}")
            lines.append("")
            lines.append(f"  async abort(): Promise<boolean> {{")
            lines.append(f"    // Phase 2: abort all if any failed.")
            lines.append(f"    return true;")
            lines.append(f"  }}")
            lines.append("}")

        else:
            lines.append(f"export class {tx.id.replace('-', '_').title().replace('_', '')}Outbox {{")
            lines.append(f"  // Outbox pattern for '{tx.id}'.")
            lines.append("")
            lines.append(f"  @PrimaryGeneratedColumn('uuid')")
            lines.append(f"  id!: string;")
            lines.append("")
            lines.append(f"  @Column()")
            lines.append(f"  aggregateType!: string;")
            lines.append("")
            lines.append(f"  @Column()")
            lines.append(f"  aggregateId!: string;")
            lines.append("")
            lines.append(f"  @Column()")
            lines.append(f"  eventType!: string;")
            lines.append("")
            lines.append(f"  @Column({{ nullable: true }})")
            lines.append(f"  payload: string | null;")
            lines.append("")
            lines.append(f"  @Column({{ default: false }})")
            lines.append(f"  published: boolean;")
            lines.append("}")

        lines.append("")

        filename = f"transactions/{self._to_kebab_case(tx.id)}.ts"
        return {filename: "\n".join(lines)}

    def emit_jsonb_columns(self, columns: list[JSONBColumn]) -> dict[str, str]:
        """Sinh JSONB column decorators + GIN index cho TypeORM."""
        lines: list[str] = []
        lines.append("// JSONB Column Decorators — Auto-generated by Midicoder CE.")
        lines.append("")
        lines.append("import { Column, Index } from 'typeorm';")
        lines.append("")
        lines.append("")

        for col in columns:
            lines.append(f"// JSONB column: {col.name}")
            if col.validation_mode.value != "none":
                lines.append(f"// Validation: {col.validation_mode.value}")
            if col.jsonb_indexes:
                lines.append(f"// GIN Index: {len(col.jsonb_indexes)} indexes defined")
            lines.append(f"// Usage:")
            lines.append(f"//   @Column('jsonb')")
            for idx in col.jsonb_indexes:
                lines.append(f"//   @Index('{idx.name}', {{ unique: false, spatialIndex: false }})")
            lines.append(f"//   {self._to_camel_case(col.name)}!: any;")
            lines.append("")

        lines.append("")
        lines.append("export function JsonbColumn(options: any = {}) {")
        lines.append("  return Column('jsonb', options);")
        lines.append("}")
        lines.append("")
        lines.append("")
        lines.append("export function JsonbGinIndex(name: string) {")
        lines.append("  return Index(name, { unique: false });")
        lines.append("}")

        return {"jsonb/jsonb.decorators.ts": "\n".join(lines)}
