    def emit_base_repository(self) -> dict[str, str]:
        """
        Sinh BaseEntityRepository voi CRUD + tenant isolation.

        Returns:
            Dictionary {file_path: content}
        """
        lines: list[str] = []
        lines.append("// Base Repository - CRUD base class với tenant isolation (KPI-029)")
        lines.append("// Auto-generated by Midicoder CE.")
        lines.append("")
        lines.append("import { EntityTarget, Repository } from 'typeorm';")
        lines.append("import { AppDataSource } from '../datasource';")
        lines.append("")
        lines.append("")
        lines.append("/**")
        lines.append(" * Base repository với CRUD operations và tenant isolation (KPI-029).")
        lines.append(" *")
        lines.append(" * Usage:")
        lines.append(" *   class UserRepository extends BaseEntityRepository<UserEntity> {")
        lines.append(" *     constructor() {")
        lines.append(" *       super(UserEntity);")
        lines.append(" *     }")
        lines.append(" *   }")
        lines.append(" */")
        lines.append("export abstract class BaseEntityRepository<T> {")
        lines.append("  protected repository: Repository<T>;")
        lines.append("")
        lines.append("  constructor(entityClass: EntityTarget<T>) {")
        lines.append("    this.repository = AppDataSource.getRepository(entityClass);")
        lines.append("  }")
        lines.append("")
        lines.append("  protected getRepo(): Repository<T> {")
        lines.append("    return this.repository;")
        lines.append("  }")
        lines.append("")
        lines.append("  async getById(id: string): Promise<T | null> {")
        lines.append("    return this.repository.findOne({ where: { id } as any });")
        lines.append("  }")
        lines.append("")
        lines.append("  async list(tenantId?: string): Promise<T[]> {")
        lines.append("    // KPI-029: Tu dong filter theo tenantId neu co")
        lines.append("    const where: any = {};")
        lines.append("    if (tenantId) {")
        lines.append("      where.tenantId = tenantId;")
        lines.append("    }")
        lines.append("    return this.repository.find({ where });")
        lines.append("  }")
        lines.append("")
        lines.append("  async create(entity: T): Promise<T> {")
        lines.append("    return this.repository.save(entity);")
        lines.append("  }")
        lines.append("")
        lines.append("  async update(id: string, data: Partial<T>): Promise<T | null> {")
        lines.append("    await this.repository.update(id, data);")
        lines.append("    return this.getById(id);")
        lines.append("  }")
        lines.append("")
        lines.append("  async delete(id: string): Promise<boolean> {")
        lines.append("    const result = await this.repository.delete(id);")
        lines.append("    return (result.affected ?? 0) > 0;")
        lines.append("  }")
        lines.append("}")

        return {"repositories/base-entity-repository.ts": "\n".join(lines)}

    def emit_migration(self, model: DataModel, version: str) -> dict[str, str]:
        """
        Sinh TypeORM migration file cho model.

        Args:
            model: DataModel de sinh migration
            version: Version revision ID

        Returns:
            Dictionary {file_path: content}
        """
        lines: list[str] = []
        lines.append(f"// Create {model.table_name} table")
        lines.append(f"// Revision: {version}")
        lines.append("")
        lines.append("import { MigrationInterface, QueryRunner, Table, TableIndex } from 'typeorm';")
        lines.append("")
        lines.append("")
        lines.append(f"export class Create{model.table_name}{version} implements MigrationInterface {{")
        lines.append("")
        lines.append("  public async up(queryRunner: QueryRunner): Promise<void> {")

        # Create table
        lines.append(f'    await queryRunner.createTable(new Table({{')
        lines.append(f'      name: "{model.table_name}",')
        lines.append('      columns: [')

        for col in model.columns:
            orm_type = _TYPEORM_TYPE_MAP.get(col.column_type, "varchar")
            col_name = TypeORMEmitter._to_camel_case(col.name)
            col_def = f'        new TableColumn({{ name: "{col_name}", type: "{orm_type}"'
            if col.primary_key:
                col_def += ', isPrimary: true'
            if col.required and not col.primary_key:
                col_def += ', isNullable: false'
            if col.unique:
                col_def += ', isUnique: true'
            if col.max_length and orm_type in ("varchar", "nvarchar"):
                col_def += f', length: {col.max_length}'
            col_def += '})'
            lines.append(col_def + ',')

        lines.append('      ],')
        lines.append('    }), true);')

        # Create indexes
        for idx in model.indexes:
            lines.append(f'    await queryRunner.createIndex(new TableIndex({{')
            lines.append(f'      name: "{idx.name}",')
            lines.append(f'      table: "table_name",')
            lines.append(f'      columnNames: {idx.columns},')
            lines.append(f'      isUnique: {idx.unique},')
            lines.append('    }), true);')

        lines.append('  }')
        lines.append('')
        lines.append('  public async down(queryRunner: QueryRunner): Promise<void> {')
        lines.append(f'    await queryRunner.dropTable("{model.table_name}");')
        lines.append('  }')
        lines.append('}')
        lines.append('')
        lines.append('export class CreateMigration implements MigrationInterface {')
        lines.append('  public async up(queryRunner: QueryRunner): Promise<void> {')
        lines.append('    await new CreateMigration().up(queryRunner);')
        lines.append('  }')
        lines.append('  public async down(queryRunner: QueryRunner): Promise<void> {')
        lines.append('    await new CreateMigration().down(queryRunner);')
        lines.append('  }')
        lines.append('}')

        filename = f"migrations/{version}-Create{model.table_name}.ts"
        return {filename: "\n".join(lines)}

