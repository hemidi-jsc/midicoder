    """
    Emitter để sinh cache files cho FastAPI.

    Render cache config từ CacheCollection sang Python files
    sử dụng Jinja2 templates tại stacks/fastapi/cp_backend_cache/.

    KPI-029: Tenant isolation qua key prefix.
    """

    def generate(
        self,
        collection: CacheCollection,
        stack: str = "fastapi",
    ) -> dict[str, str]:
        """
        Sinh cache files cho FastAPI.

        Args:
            collection: Collection chứa cache config
            stack: Stack name (mặc định: fastapi)

        Returns:
            Dictionary {file_path: content}
        """
        files: dict[str, str] = {}

        if not collection.profiles:
            return files

        # Xác định backends được sử dụng
        backends = {p.backend for p in collection.profiles}

        if CacheBackend.REDIS in backends:
            # Sinh redis client + connection pool
            files["cache/redis.py"] = self._emit_redis_client(collection)

        if CacheBackend.MEMCACHED in backends:
            files["cache/memcached.py"] = self._emit_memcached_client(collection)

        # Sinh cache strategies
        files["cache/cache_strategy.py"] = self._emit_cache_strategy(collection)

        # Sinh cache decorators
        files["cache/cache_decorators.py"] = self._emit_cache_decorators(collection)

        # Sinh cache invalidation service
        files["cache/cache_invalidate.py"] = self._emit_cache_invalidate(collection)

        # Sinh CDN cache middleware (nếu có CDN config)
        if collection.cdn_layers:
            files["cache/cdn_cache.py"] = self._emit_cdn_cache(collection)

        # Sinh stampede prevention (nếu có config)
        if collection.stampede_prevention:
            files["cache/stampede_prevention.py"] = self._emit_stampede_prevention(collection)

        # Sinh cache warmup (nếu có warmup config)
        if collection.warmup_config:
            files["cache/cache_warmup.py"] = self._emit_cache_warmup(collection)

        # Sinh multi-tier cache (nếu có tiers)
        if collection.tiers:
            files["cache/multi_tier.py"] = self._emit_multi_tier(collection)

        # Sinh __init__.py
        files["cache/__init__.py"] = self._emit_init(collection)

        return files

