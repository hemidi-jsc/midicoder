def get_cache_control_headers(
    public: bool = True,
    ttl: int | None = None,
    stale_while_revalidate: int = 60,
    stale_if_error: int = 300,
) -> dict[str, str]:
    """Xay dung Cache-Control headers cho CDN responses."""
    actual_ttl = ttl if ttl is not None else DEFAULT_CDN_TTL
    directives = ["public" if public else "private", f"max-age={{actual_ttl}}"]
    directives.append(f"stale-while-revalidate={{stale_while_revalidate}}")
    directives.append(f"stale-if-error={{stale_if_error}}")
    return {{"Cache-Control": ", ".join(directives)}}


async def cdn_cache_middleware(request: Request, call_next):
    """FastAPI middleware để add CDN cache headers."""
    response = await call_next(request)

    # Chỉ cache GET requests
    if request.method == "GET":
        response.headers["Cache-Control"] = ", ".join([
            "public",
            f"max-age={{DEFAULT_CDN_TTL}}",
            "stale-while-revalidate=60",
            "stale-if-error=300",
        ])
        response.headers["Vary"] = "Accept-Encoding"

    return response


