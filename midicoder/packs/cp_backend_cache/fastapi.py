_lock_prefix = "__cache_lock:"
_DEFAULT_LOCK_TTL = {lock_ttl}
_DEFAULT_LOCK_TIMEOUT = {lock_timeout}


async def _acquire_lock(
    key: str,
    tenant_id: str | None = None,
    ttl: int = _DEFAULT_LOCK_TTL,
) -> bool:
    """Acquire distributed mutex lock trên Redis."""
    redis = get_redis()
    lock_key = get_key_with_tenant(f"{{_lock_prefix}}{{key}}", tenant_id)
    acquired = await redis.set(lock_key, "1", nx=True, ex=ttl)
    return bool(acquired)


async def _release_lock(
    key: str,
    tenant_id: str | None = None,
) -> None:
    """Release distributed mutex lock."""
    redis = get_redis()
    lock_key = get_key_with_tenant(f"{{_lock_prefix}}{{key}}", tenant_id)
    await redis.delete(lock_key)


async def stampede_safe_get(
    cache_get: Callable,
    cache_set: Callable,
    loader: Callable,
    key: str,
    tenant_id: str | None = None,
    ttl: int = 300,
) -> Any:
    """
    Lấy giá trị từ cache với stampede prevention (strategy: {strategy}).

    Khi cache miss, chỉ 1 request thực sự load data, các request khác wait.
    """
    cached = await cache_get(key, tenant_id=tenant_id)
    if cached is not None:
        return cached

    # Thử acquire lock
    acquired = await _acquire_lock(key, tenant_id)

    if acquired:
        try:
            # Double-check sau khi acquire lock
            cached = await cache_get(key, tenant_id=tenant_id)
            if cached is not None:
                return cached

            # Load data và set vào cache
            value = loader() if callable(loader) else loader
            if hasattr(value, "__await__"):
                value = await value
            await cache_set(key, value, ttl, tenant_id=tenant_id)
            return value
        finally:
            await _release_lock(key, tenant_id)
    else:
        # Không acquire được lock — wait và retry với stale data
        await asyncio.sleep(0.1)
        retry_count = 0
        while retry_count < {{_DEFAULT_LOCK_TIMEOUT * 10}}:
            cached = await cache_get(key, tenant_id=tenant_id)
            if cached is not None:
                return cached
            await asyncio.sleep(0.1)
            retry_count += 1

        # Timeout — fallback: load data trực tiếp (không cache)
        value = loader() if callable(loader) else loader
        if hasattr(value, "__await__"):
            value = await value
        return value
