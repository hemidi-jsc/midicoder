    async def invalidate_key(self, key: str, tenant_id: str | None = None) -> bool:
        """Xoa key khoi cache."""
        redis = get_redis()
        full_key = get_key_with_tenant(key, tenant_id)
        return (await redis.delete(full_key)) > 0

    async def invalidate_pattern(self, pattern: str, tenant_id: str | None = None) -> int:
        """Xoa batch keys theo glob pattern."""
        redis = get_redis()
        full_pattern = get_key_with_tenant(pattern, tenant_id)
        deleted = 0
        cursor = "0"
        while True:
            cursor, keys = await redis.scan(cursor, match=full_pattern, count=100)
            if keys:
                await redis.delete(*keys)
                deleted += len(keys)
            if cursor == "0":
                break
        return deleted

    async def invalidate_all(self, tenant_id: str | None = None) -> int:
        """Xoa tat ca cache keys cua tenant."""
        prefix = f"{tenant_id}:" if tenant_id else ""
        return await self.invalidate_pattern(f"{prefix}*")
